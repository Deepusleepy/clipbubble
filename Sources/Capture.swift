import AppKit

/// Polls the system clipboard and records every change, including Universal Clipboard copies from iPhone.
final class Capture {
    private let db = DB()
    private let queue = DispatchQueue(label: "clipbubble.capture")
    private var count = NSPasteboard.general.changeCount
    private var seenCount = NSPasteboard.general.changeCount
    private var seenAt = Date()
    /// The latest capture and the one before it, to spot tools that paste through the clipboard.
    private var last: (hash: String, at: Date, inserted: Bool)?
    private var previousHash: String?
    private var timer: DispatchSourceTimer?
    private let onChange: () -> Void

    /// Password managers mark secrets with these; never record them.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    init(onChange: @escaping () -> Void) {
        self.onChange = onChange
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now(), repeating: 0.4)
        t.setEventHandler { [weak self] in self?.poll() }
        t.resume()
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        let now = Date()
        // Let the clipboard settle first. Paste-through tools like Wispr Flow put text on it, press ⌘V and then
        // restore the old contents; reading during that window could make them paste the wrong thing.
        if pb.changeCount != seenCount { seenCount = pb.changeCount; seenAt = now; return }
        guard seenCount != count, now.timeIntervalSince(seenAt) >= 0.6 else { return }
        count = seenCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.skipTypes), let clip = read(pb) else { return }
        if clip.hash == last?.hash { return }

        // The previous contents came straight back, so what we just saw was a paste-through: drop it,
        // and don't bump the restored item.
        if clip.hash == previousHash, let l = last, now.timeIntervalSince(l.at) < 2.5 {
            if l.inserted { db.delete(hash: l.hash) }
            last = (clip.hash, now, false)
            previousHash = nil
            onChange()
            return
        }

        let source = types.contains("com.apple.is-remote-clipboard")
            ? "iPhone" : (NSWorkspace.shared.frontmostApplication?.localizedName ?? "Mac")
        let inserted = !db.exists(hash: clip.hash)
        db.upsert(kind: clip.kind, text: clip.text, file: clip.file, source: source, hash: clip.hash)
        previousHash = last?.hash
        last = (clip.hash, now, inserted)
        onChange()
    }

    private func read(_ pb: NSPasteboard) -> (kind: String, text: String, file: String?, hash: String)? {
        let string = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let looksLikeURL = string.map { !$0.contains(" ") && !$0.contains("\n") && $0.hasPrefix("http") } ?? false

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ("file", paths, nil, "f:" + sha(paths))
        }
        if string?.isEmpty ?? true || looksLikeURL, let png = imagePNG(pb) {
            let h = sha(png)
            let path = Paths.images.appendingPathComponent(h + ".png").path
            if !FileManager.default.fileExists(atPath: path) { FileManager.default.createFile(atPath: path, contents: png) }
            return ("image", "", path, "i:" + h)
        }
        if let raw = pb.string(forType: .string), !(string?.isEmpty ?? true) {
            return ("text", raw, nil, "t:" + sha(raw))
        }
        return nil
    }

    private func imagePNG(_ pb: NSPasteboard) -> Data? {
        if let d = pb.data(forType: .png) { return d }
        for t in [NSPasteboard.PasteboardType.tiff, .init("public.jpeg"), .init("public.heic")] {
            if let d = pb.data(forType: t), let rep = NSBitmapImageRep(data: d) {
                return rep.representation(using: .png, properties: [:])
            }
        }
        return nil
    }
}

/// Watches the macOS screenshot folder and hands every new screenshot or recording to `onNew`.
final class ScreenshotWatcher {
    let folder: URL
    private var known: Set<URL> = []
    private var source: DispatchSourceFileSystemObject?
    private var pending: DispatchWorkItem?
    private let onNew: (URL, Date) -> Void

    init(onNew: @escaping (URL, Date) -> Void) {
        self.onNew = onNew
        let raw = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location") ?? "~/Desktop"
        folder = URL(fileURLWithPath: (raw as NSString).expandingTildeInPath, isDirectory: true)
        known = Set(listing())
        start()
    }

    /// Retries until macOS grants access to the folder (the privacy prompt may still be open).
    private func start() {
        let fd = open(folder.path, O_EVTONLY)
        guard fd >= 0 else {
            DispatchQueue.main.asyncAfter(deadline: .now() + 5) { [weak self] in self?.start() }
            return
        }
        known = Set(listing())
        let src = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: [.write, .rename], queue: .main)
        src.setEventHandler { [weak self] in
            guard let self else { return }
            self.pending?.cancel()
            let w = DispatchWorkItem { self.scan() }
            self.pending = w
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.4, execute: w)
        }
        src.setCancelHandler { close(fd) }
        src.resume()
        source = src
    }

    static func created(_ u: URL) -> Date {
        (try? u.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast
    }

    /// Everything already in the folder from the last `days` days, for backfilling history.
    func existing(days: Double) -> [(URL, Date)] {
        let cutoff = Date().addingTimeInterval(-days * 86400)
        return listing().map { ($0, Self.created($0)) }.filter { $0.1 > cutoff }
    }

    private func listing() -> [URL] {
        let urls = (try? FileManager.default.contentsOfDirectory(
            at: folder, includingPropertiesForKeys: [.creationDateKey], options: [.skipsHiddenFiles])) ?? []
        return urls.filter { isImagePath($0.path) || ["mov", "mp4"].contains($0.pathExtension.lowercased()) }
    }

    private func scan() {
        let now = listing()
        let fresh = now.filter { !known.contains($0) }
        known = Set(now)
        // Only files created in the last two minutes, so moving old files in doesn't count as new.
        let cutoff = Date().addingTimeInterval(-120)
        for (url, date) in fresh.map({ ($0, Self.created($0)) }).filter({ $0.1 > cutoff }).sorted(by: { $0.1 < $1.1 }) {
            onNew(url, date)
        }
    }
}
